export const dictionaries = { en, th } as const;

function transformDictionaryText<T>(value: T, transform: (text: string) => string): T {
  if (typeof value === "string") return transform(value) as T;
  if (typeof value === "function") {
    return ((...args: unknown[]) => {
      const result = (value as unknown as (...parameters: unknown[]) => unknown)(...args);
      return typeof result === "string" ? transform(result) : result;
    }) as T;
  }
  if (Array.isArray(value)) return value.map((item) => transformDictionaryText(item, transform)) as T;
  if (typeof value === "object" && value !== null) {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, transformDictionaryText(item, transform)]),
    ) as T;
  }
  return value;
}

function makeThaiTextUnbreakable<T>(value: T): T {
  return transformDictionaryText(value, (text) => text
    .replaceAll("ศรีอู่ทองแกรนด์โฮเทล", "ศ\u2060ร\u2060ี\u2060อ\u2060ู\u2060่\u2060ท\u2060อ\u2060ง\u2060แ\u2060ก\u2060ร\u2060น\u2060ด\u2060์\u2060โ\u2060ฮ\u2060เ\u2060ท\u2060ล")
    .replaceAll("ศรีอู่ทองแกรนด์", "ศ\u2060ร\u2060ี\u2060อ\u2060ู\u2060่\u2060ท\u2060อ\u2060ง\u2060แ\u2060ก\u2060ร\u2060น\u2060ด\u2060์")
    .replaceAll("ศรีอู่ทอง", "ศ\u2060ร\u2060ี\u2060อ\u2060ู\u2060่\u2060ท\u2060อ\u2060ง"));
}

function makeEnglishTextUnbreakable<T>(value: T): T {
  return transformDictionaryText(value, (text) => text
    .replaceAll("Sri U-Thong Grand", "Sri\u00A0U\u2011Thong\u00A0Grand")
    .replaceAll("Sri U-Thong", "Sri\u00A0U\u2011Thong")
    .replaceAll("U-Thong", "U\u2011Thong"));
}

export function getDictionary(locale: Locale) {
  const dict = dictionaries[locale];
  if (locale === "th") {
    return makeThaiTextUnbreakable(dict);
  }
  return makeEnglishTextUnbreakable(dict);
}
